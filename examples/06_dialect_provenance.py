"""Example — what answers for a lect, and why.

Because a dialect is an orthography2ipa lect spec, the pipeline that produced a
transcription is inspectable: ``tugaphone.pipeline`` returns the
orthography2ipa ``Pipeline`` tugaphone runs for a lect. In pt-PT, a word the
rules get wrong is answered by the o2i-lexicons residual lexicon, and every
other word is generated by the lattice. A sub-lect such as pt-PT-x-porto has no
lexicon, so its rules answer every word.

Run::

    python examples/06_dialect_provenance.py
"""
from orthography2ipa import G2P

import tugaphone
from tugaphone import resolve_lect


def main() -> None:
    for code in ["pt-PT", "pt-PT-x-porto", "pt-BR"]:
        lect = resolve_lect(code)
        pipeline = tugaphone.pipeline(lect)
        print(f"{code} → lect {lect}, {len(pipeline.lexicon)} lexicon entries")

    print("\nlexicon vs lattice-generated (pt-PT):")
    lexicon = tugaphone.pipeline("pt-PT").lexicon
    engine = G2P("pt-PT", pipeline=tugaphone.pipeline("pt-PT"))
    for word in ["antidumping", "blorfante"]:  # in-lexicon vs invented
        source = "lexicon" if word in lexicon else "lattice"
        print(f"  {word:12s} → {engine.transcribe(word)}  ({source})")


if __name__ == "__main__":
    main()
